def load_knowledge(directory: Path | None = None) -> str:
    """Склеивает knowledge/*.md в порядке: planning.md, about_me.md, остальные по имени."""
    directory = directory or settings.knowledge_dir
    if not directory.exists():
        log.warning("Папка базы знаний не найдена: %s", directory)
        return ""
    preferred = ["planning.md", "about_me.md"]
    files = [directory / name for name in preferred if (directory / name).exists()]
    files += sorted(p for p in directory.glob("*.md") if p.name not in preferred)
    chunks = []
    for path in files:
        text = path.read_text(encoding="utf-8").strip()
        if text:
            chunks.append(f"=== {path.name} ===\n{text}")
    return "\n\n".join(chunks)


def build_system_prompt(directory: Path | None = None) -> str:
    knowledge = load_knowledge(directory)
    if not knowledge:
        return BASE_PROMPT
    return BASE_PROMPT + "\n\nБАЗА ЗНАНИЙ (методология и профиль Сони; ссылки на § ниже — сюда):\n\n" + knowledge


SYSTEM_PROMPT = build_system_prompt()
